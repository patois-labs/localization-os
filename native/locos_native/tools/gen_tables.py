"""Generate src/tables.rs (Python's character classes) and src/stamps.rs (reference stamps).

Run from the local-tms root with the app's Python (the SAME minor version the image ships):

    .venv\\Scripts\\python.exe native\\locos_native\\tools\\gen_tables.py           # both files
    .venv\\Scripts\\python.exe native\\locos_native\\tools\\gen_tables.py --stamps  # stamps.rs only

Why generated: Python `re` and Rust disagree on Unicode classes (`\\w` includes combining marks in
Rust, not in Python; `\\s` includes U+001C..U+001F in Python, not in Rust `char::is_whitespace`;
`(?i)i` also matches U+0130 and U+0131 in Python). So the crate never uses Rust's own classes: it
reads these tables, measured from this interpreter's `re`, and records the Unicode version they
came from. The loader refuses the module when the running Python reports a different one.

stamps.rs holds one fingerprint per native function, computed by app.services.native.fingerprint
over the Python reference source. Re-stamp ONLY after the Rust side was changed to match an edited
reference and the parity suite (tests/verify_native_parity.py) is green: a stale stamp is what
switches the native function off (Python runs instead) when the reference moves.
"""

from __future__ import annotations

import os
import re
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.dirname(HERE)
ROOT = os.path.dirname(os.path.dirname(CRATE))

MAX = 0x110000


def _chars():
    for c in range(MAX):
        if 0xD800 <= c <= 0xDFFF:
            continue  # lone surrogates never reach Rust (the fast path needs valid UTF-8)
        yield c


def _ranges(pred) -> list[tuple[int, int]]:
    out: list[list[int]] = []
    for c in _chars():
        if pred(chr(c)):
            if out and out[-1][1] == c - 1:
                out[-1][1] = c
            else:
                out.append([c, c])
    return [(a, b) for a, b in out]


def _rs_ranges(name: str, ranges) -> str:
    body = ",\n".join(f"    (0x{a:X}, 0x{b:X})" for a, b in ranges)
    return f"pub static {name}: &[(u32, u32)] = &[\n{body},\n];\n"


# Every letter that appears inside a (?i:...) group of segment._ABBREV_RULES, as the pattern
# character. sre lower-cases a cased pattern literal, so 'B' and 'b' share one set.
CI_LETTERS = "abcdefghijklmnopqrstuvwxyz" + "àáú"


def gen_tables() -> str:
    word = re.compile(r"\w")
    space = re.compile(r"\s")
    digit = re.compile(r"\d")
    ws = _ranges(lambda ch: space.match(ch) is not None)
    ws_isspace = _ranges(str.isspace)
    if ws != ws_isspace:
        raise SystemExit("re \\s and str.isspace disagree: split/strip and \\s need two tables")
    word_r = _ranges(lambda ch: word.match(ch) is not None)
    digit_r = _ranges(lambda ch: digit.match(ch) is not None)
    # The locale check in the abbreviation rules compares a lower-cased language subtag with
    # ASCII codes; the Rust side compares ASCII case-insensitively, which is exact only while
    # no non-ASCII character lower-cases to ASCII other than KELVIN SIGN (lower 'k', a letter
    # none of the rule languages de/fr/es/pt/it/nl contains).
    to_ascii = [c for c in _chars() if c >= 128 and chr(c).lower().isascii()]
    if to_ascii != [0x212A]:
        raise SystemExit(f"non-ASCII chars lower-casing to ASCII changed: {to_ascii}")
    # Case-insensitive equivalence sets, measured from sre itself.
    any_ci = re.compile("(?i)[" + CI_LETTERS + "]")
    cand = [c for c in _chars() if any_ci.fullmatch(chr(c))]
    arms = []
    for letter in CI_LETTERS:
        p = re.compile("(?i)" + re.escape(letter))
        eq = [c for c in cand if p.fullmatch(chr(c))]
        alts = " | ".join(f"'\\u{{{c:X}}}'" for c in eq)
        arms.append(f"        '\\u{{{ord(letter):X}}}' => matches!(c, {alts}),")
    for letter in CI_LETTERS.upper()[:26]:
        p = re.compile("(?i)" + letter)
        eq = [c for c in cand if p.fullmatch(chr(c))]
        alts = " | ".join(f"'\\u{{{c:X}}}'" for c in eq)
        arms.append(f"        '\\u{{{ord(letter):X}}}' => matches!(c, {alts}),")
    ci_fn = (
        "/// Python `(?i)` equality of a pattern letter with a text character (sre semantics).\n"
        "/// Pattern characters outside the table are uncased: plain equality.\n"
        "pub fn ci_eq(pat: char, c: char) -> bool {\n    match pat {\n"
        + "\n".join(arms)
        + "\n        _ => pat == c,\n    }\n}\n"
    )
    head = (
        "// GENERATED by tools/gen_tables.py from Python "
        f"{sys.version.split()[0]} (unicodedata {unicodedata.unidata_version}). Do not edit.\n"
        "// Character classes exactly as Python `re` / str methods see them.\n\n"
        f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";\n\n'
    )
    return (
        head
        + "/// re `\\s` == str.isspace (also what str.split() / str.strip() use).\n"
        + _rs_ranges("SPACE", ws)
        + "\n/// re `\\w` (str patterns, no flags).\n"
        + _rs_ranges("WORD", word_r)
        + "\n/// re `\\d` (str patterns: Unicode decimal digits, category Nd).\n"
        + _rs_ranges("DIGIT", digit_r)
        + "\n"
        + ci_fn
    )


def gen_stamps() -> str:
    sys.path.insert(0, ROOT)
    os.chdir(ROOT)
    from tests._bootstrap import init_env

    init_env("loctms_native_stamps_")
    os.environ["LOCOS_NATIVE"] = "0"  # fingerprint the pure-Python references
    from app.services import native, quality_common, segment, tm_common  # noqa: F401

    lines = [
        "// GENERATED by tools/gen_tables.py --stamps. Do not edit by hand.",
        "// One fingerprint per native function over its Python reference (native.SPECS).",
        "// A mismatch at import makes the loader keep the Python function for that name.",
        "",
        "pub static STAMPS: &[(&str, &str)] = &[",
    ]
    for name in sorted(native.SPECS):
        lines.append(f'    ("{name}", "{native.fingerprint(name)}"),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def _write(path: str, text: str) -> None:
    with open(path, "wb") as f:
        f.write(text.encode("utf-8"))
    print(f"wrote {os.path.relpath(path, ROOT)}")


def main(argv) -> int:
    src = os.path.join(CRATE, "src")
    if "--stamps" not in argv:
        _write(os.path.join(src, "tables.rs"), gen_tables())
    _write(os.path.join(src, "stamps.rs"), gen_stamps())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
