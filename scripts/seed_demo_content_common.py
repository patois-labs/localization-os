# Make the repo root importable when this file is run directly as a script
# (python scripts/seed_demo_content.py) — only scripts/ is on sys.path then.
# --- identity / markers -------------------------------------------------------
# The seed marker is stamped into the created_by column of the Glossary and the
# demo Project so --cleanup can identify EXACTLY the rows a prior seed created
# (never a same-named row a human made). SegmentTM has no such column, so its rows
# are identified by (target project, source hash, locale pair) against the known
# source strings below.
# --- GLOSSARY (25 terms x 5 locales) ------------------------------------------
# Each term: (source_term, {es-ES, fr-FR, de-DE, ja-JP, zh-CN}, dnt). A DNT brand
# term keeps the source unchanged in every locale (dnt=True; target = source).
# order: es-ES, fr-FR, de-DE, ja-JP, zh-CN
# --- Do-Not-Translate brand terms (kept verbatim in every locale) ---
# --- TRANSLATION MEMORY (100 source strings x 5 locales) ----------------------
# Each row: (en-US, es-ES, fr-FR, de-DE, ja-JP, zh-CN). Varied lengths; some carry
# {placeholders}; several are near-duplicates of a neighbor (fuzzy-match fodder).
# --- console output (ASCII-safe on any Windows console) -----------------------
def _emit(line: str = "") -> None:
    """Print one line, degrading non-ASCII to backslash escapes on a cp1252 console
    (reuses the app's own _write_ascii_safe so this script never dies mid-run)."""
    try:
        from app.cli._common import _write_ascii_safe

        _write_ascii_safe(sys.stdout, line + "\n")
    except Exception:
        sys.stdout.write(line.encode("ascii", "backslashreplace").decode("ascii") + "\n")
