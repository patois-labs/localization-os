"""Central multi-org scope classification of every in-process CLI verb (#556).

#515 closed the unscoped verbs one at a time; the next verb someone adds would ship unscoped
under multi-org. This module is the single table that stops that: every leaf of the argparse
tree (a space-joined path such as ``project create``) is listed in exactly one of three
classes, `app.cli.__main__.main` applies the matching gate BEFORE the verb body runs, and
`tests/verify_cli_scope_classification.py` fails when the parser has a leaf this table does
not name (or the table names a leaf the parser no longer has). A new verb therefore has to be
classified in the same change that adds it.

  ORG_SCOPED    touches tenant rows. Gate: `require_org_scope` (an in-process command under
                multi-org needs ``--org <id>``, or ``--operator`` with LOC_TMS_OPERATOR_KEY).
  OPERATOR_ONLY inherently cross-org, or it writes something every org shares (#515: retention,
                SRX switches, LDAP/OIDC config, the LQA rulebook, connector
                token-regen). Gate: `require_operator` (``--operator`` only; ``--org`` cannot
                scope it). The verbs keep their own require_operator call as a second wall.
  INSTALL_WIDE  host verbs with no tenant rows and no shared-setting write the gate covers
                (database file, keyfiles, status readers, provider keys, ledger, static catalogs).
                No gate: in-process CLI is the host operator surface and these never touch an
                org's rows.

With the gate OFF (every real install) both gates return immediately: behavior is byte-identical.
Remote mode (``--remote``) never runs the central gate: the key scopes it server-side, and the
verbs that cannot run remotely refuse it themselves.

Documented in: docs/architecture/surfaces-and-parity.md
"""

