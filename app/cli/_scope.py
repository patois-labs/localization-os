#: Every classified leaf -> its class, built from the three sets above (a leaf is in only one).
VERB_SCOPE: dict[str, str] = {
    **dict.fromkeys(_ORG_SCOPED_VERBS, ORG_SCOPED),
    **dict.fromkeys(_OPERATOR_ONLY_VERBS, OPERATOR_ONLY),
    **dict.fromkeys(_INSTALL_WIDE_VERBS, INSTALL_WIDE),
}


def iter_leaves(parser: argparse.ArgumentParser, path: tuple = ()):
    """Yield ``(path_tuple, leaf_parser)`` for every leaf (a parser with no subcommands)."""
    subs = [a for a in parser._actions if isinstance(a, argparse._SubParsersAction)]
    if not subs:
        yield path, parser
        return
    for action in subs:
        for name, sub in action.choices.items():
            yield from iter_leaves(sub, (*path, name))


def stamp_leaves(parser: argparse.ArgumentParser) -> None:
    """Record each leaf's verb path on its parser defaults (``_verb_path``) so the dispatcher
    knows which verb ran without re-deriving it from argv."""
    for path, leaf in iter_leaves(parser):
        if path:
            leaf.set_defaults(_verb_path=" ".join(path))


def leaf_paths(parser: argparse.ArgumentParser) -> set[str]:
    """Every leaf verb path of the parser, space-joined (the bare root is not a verb)."""
    return {" ".join(path) for path, _leaf in iter_leaves(parser) if path}


def unclassified(parser: argparse.ArgumentParser) -> list[str]:
    """Leaves of the parser that VERB_SCOPE does not name (must be empty)."""
    return sorted(leaf_paths(parser) - set(VERB_SCOPE))


def stale(parser: argparse.ArgumentParser) -> list[str]:
    """Table entries naming a verb the parser no longer has (must be empty)."""
    return sorted(set(VERB_SCOPE) - leaf_paths(parser))


def scope_of(verb_path: str) -> str:
    """The class of a verb path. An unclassified verb is treated as ORG_SCOPED (fail closed:
    the strictest gate that still lets ``--org`` work); the static test keeps that case empty."""
    return VERB_SCOPE.get(verb_path, ORG_SCOPED)
