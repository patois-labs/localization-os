"""``app.kernel`` -- the loc-core translation-kernel API (composable-core phase 4, K1).

A PACKAGE of ALIAS SHIMS. Importing ``app.kernel`` installs ONE lazy ``sys.meta_path``
finder that maps ``app.kernel.<name>`` onto the real module it re-exports, so
``app.kernel.tm IS app.services.tm`` -- the facade never re-implements anything. Nothing is
imported eagerly: each alias resolves only on its first ``import app.kernel.<name>``, which is
what lets ``app/kernel/pipeline.py`` embed just the engine (~58 ``app.*`` modules, no
FastAPI/Jinja/Starlette, no ``smtplib``/PyJWT) instead of the whole platform.

Alias families (``_ALIAS_MAP``, a COMMITTED BUILD-TIME LITERAL -- never computed at import;
regenerated by the K1 builder from the AST union of ``app.services`` modules imported across
``app/web`` + ``app/cli`` (+ ``app/backoffice`` when the literal was generated; that
shell was removed 2026-09-20 and the recorded surface did not shrink), minus the two
shell-facing services and the two phantoms):
  * SERVICES  ``app.kernel.<svc>``        -> ``app.services.<svc>``   (the surface)
  * PORTS     ``app.kernel.ports.<port>`` -> ``app.ports.<port>``     (NAMESPACED -- B2: the
              live ``scheduler`` service-vs-port name collision means the 6 ports may not be
              flat under ``app.kernel``)
  * SPINE     ``app.kernel.<spine>``      -> ``app.<spine>``          (config/db/models/features)

The finder's load-bearing pieces are proven against a synthetic replica (rounds 3-4):
insert(0) not append; a DISCRIMINATING deny arm (raise, never a bare ``None``); a loader that
carries BOTH names and RESTORES the real module's ``__spec__`` (module_from_spec clobbers it,
which would make ``importlib.reload`` a silent no-op); ports NAMESPACED; a name-matched
idempotence guard. See ``tests/verify_kernel_facade.py``.

STRUCTURAL RULE (enforced by review + the finder's own fall-through arm): ``app/kernel/`` may
contain ONLY alias-install code + DIRECT-CHILD re-export shims (today just ``pipeline.py``).
NO real service body, NO subpackage, NO depth->=3 file -- the deny arm's fall-through is
``count(".") == 2`` plus a ``<leaf>.py`` FILE test, so a real subpackage would be DENIED on
first import.

Imports are UNDERSCORE-ALIASED (round-3 F-7): the lazily-invoked finder/loader reference them
at CALL time (long after module init), so they cannot be ``del``'d; underscore names keep them
OFF ``app.kernel``'s PUBLIC surface (L1) without breaking the finder. No public
``sys``/``importlib``/``os`` on ``app.kernel``.

Documented in: docs/architecture/kernel-and-ports.md
"""

