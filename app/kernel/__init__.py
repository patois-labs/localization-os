def _bind(alias, module):
    """F-6: setattr the resolved module onto its parent kernel package under the ALIAS name
    (``module.__name__`` is the TARGET after the F-8 restore, so we cannot derive the alias
    from it). This is the same package-attribute binding Train 4 test-pinned for
    ``from app import config`` -- under a lazy finder there is nothing to bind before first
    import, so the loader does it here, after resolution."""
    parent, _, child = alias.rpartition(".")
    p = _sys.modules.get(parent)
    if p is not None:
        setattr(p, child, module)


class _KernelAliasLoader(_abc.Loader):
    def __init__(self, alias, target):
        self._alias = alias
        self._target = target

    def create_module(self, spec):
        module = _importlib.import_module(self._target)  # alias IS the real module; the
        # target is NOT a key in _ALIAS_MAP, so the finder is never re-entered for it (no
        # RecursionError). F-8: module_from_spec's _init_module_attrs is about to overwrite the
        # REAL module's __spec__ with this alias spec's; stash the identity to restore below,
        # else importlib.reload() (keyed off __spec__.name) silently becomes a no-op. Capturing
        # all four is DEFENSIVE (only __spec__ is actually clobbered -- __name__/__loader__/
        # __package__ are guarded by override=False -- but a future CPython could change that).
        self._identity = (module.__name__, module.__spec__, module.__loader__, module.__package__)
        return module

    def exec_module(self, module):
        # The real module already executed under app.services.*/app.* -- do NOT re-run it.
        (module.__name__, module.__spec__, module.__loader__, module.__package__) = (
            self._identity
        )  # F-8: restore the identity
        _bind(self._alias, module)  # F-6/B3: bind under alias


class _KernelAliasFinder(_abc.MetaPathFinder):
    def find_spec(self, fullname, path=None, target=None):
        tgt = _ALIAS_MAP.get(fullname)
        if tgt is not None:
            return _util.spec_from_loader(fullname, _KernelAliasLoader(fullname, tgt))
        if fullname.startswith("app.kernel."):
            # F-2: a DIRECT child of app.kernel backed by a REAL file (today only pipeline.py)
            # falls through to the standard PathFinder.
            if fullname.count(".") == 2 and _os.path.exists(
                _os.path.join(_HERE, fullname.rpartition(".")[2] + ".py")
            ):
                return None
            # F-2: DENY every OTHER unmapped app.kernel.* name here, never None -- an aliased
            # package's __path__ IS the real target dir, so a bare None lets PathFinder load a
            # silent DUPLICATE under the alias. Raising propagates directly as the import error.
            raise ModuleNotFoundError(f"{fullname} is not on the kernel surface", name=fullname)
        return None  # non-app.kernel names: untouched


def _install():
    # F-11: never stack a second finder after a sys.modules purge + re-import. Match by class
    # NAME, not isinstance: a purge re-executes this module and REBINDS _KernelAliasFinder to a
    # new class object, so a surviving old-class instance fails isinstance and a duplicate would
    # be inserted anyway. The surviving old finder resolves correctly (its _ALIAS_MAP is a
    # byte-identical committed literal), so keeping it is safe.
    if not any(type(f).__name__ == "_KernelAliasFinder" for f in _sys.meta_path):
        _sys.meta_path.insert(0, _KernelAliasFinder())  # F-1: FRONT, not append


_install()
del _install
