"""Named-port registry for composable-core phase 1 (FROZEN in Train H).

This package NAMES the internal ports the app already has: a small interface, a name-keyed
registry, and an override seam the default resolves through. Each port gets its OWN module
under ``app/ports/`` that self-registers its default adapter at import; this ``__init__``
holds ONLY the generic registry machinery.

THE PATTERN (mirrors MTEngine, the existence-proof port)
--------------------------------------------------------
MTEngine is ALREADY a port and is deliberately NOT moved here:
``app.services.providers.get_provider(name)`` is its factory,
``register_provider(name, provider)`` its override seam, and ``providers._OVERRIDES``
(consulted FIRST) its precedence rule. The MTEngine boundary is NAME-LEVEL ("construct
only via ``get_provider``"), not an import edge, so it cannot be import-guarded -- stated
here, not faked.

TWO SLOTS, mirroring providers' own house pattern (``providers._OVERRIDES`` first):

  * ``_DEFAULTS``  -- written ONLY by a port module's self-registration at import time,
    via ``register_default(port, adapter)``, with **setdefault semantics**: a repeat or
    re-entrant self-registration can never clobber an already-registered default.
  * ``_OVERRIDES`` -- written ONLY by the public ``register(port, adapter)`` (tests,
    hot-swap).

``get(port)`` consults ``_OVERRIDES`` FIRST, then ``_DEFAULTS``; on a double miss it
lazily imports ``app.ports.<port>`` (which self-registers the default into ``_DEFAULTS``)
and RE-CHECKS overrides-first -- so an override set BEFORE a port module is ever imported
still wins after the import forces the default in (the suite-order determinism the
TelemetrySink security tests depend on). A genuine miss raises ``UnknownPort`` (never a
silent ``None``), the house pattern of ``get_provider``'s ``UnknownProviderError``.

IDENTITY IS NOT SWAPPABLE
-------------------------
``register("identity", ...)`` (and ``register_default``) RAISE ``PortRegistrationRefused``
-- a HARD refusal, not a freeze-after-startup. The inbound-auth resolver
(``deps.api_identity`` / phase-0b's trust-host-auth perimeter) must not be
runtime-swappable via a mutable registry; the Identity port (Train 6) exposes its OWN
``get()`` only. This file is the mechanical guarantee, pinned by Train H's raising test.

EVENTBUS IS NOT A PORT (section-3 discrepancy 6 / section 5)
-----------------------------------------------------------
It is in-process forever by decision: two SSE producers over fresh in-process DB
sessions, with no publish/subscribe machinery to abstract. There is no
``app/ports/eventbus.py`` and no ``sse_response`` helper (explicitly forbidden).
Documented here as a named seam so a future reader does not mistake its absence for an
oversight.

ASYMMETRY, stated out loud
--------------------------
The generic ``get(port)`` returns an ADAPTER OBJECT, whereas the Identity port's own
``identity.get()`` returns a CALLABLE (``deps.api_identity``) -- a deliberate shape
difference, because Identity's "adapter" is a resolver function, not an object.

RULE FOR PORT MODULES
---------------------
A port module must NOT call ``ports.get()`` at MODULE SCOPE. A self-registering module
that also resolved another port at import could hit a partially-initialized-module
recursion. Module scope self-registers only (via ``register_default``); resolution
happens at call time. Self-register as the module's LAST statement -- a default
registered BEFORE an import failure lower in the module survives in ``_DEFAULTS`` even
though the failed module is dropped from ``sys.modules``, so a later ``get`` would return
a default from a module that never finished importing.

USAGE NOTES
-----------
``get(port)``'s ``port`` argument is expected to be a CODE LITERAL (the caller names the
port it wants); never route user/Setting/request input into it -- the lazy fallback does
``importlib.import_module(f"app.ports.{port}")``. The membership checks and teardown here
assume single-threaded registration/teardown (tests, boot); the READ path (a bare
``dict`` lookup) is safe under concurrent ``get`` once the defaults are in place.

FROZEN after Train H
--------------------
Later port trains ADD their own ``app/ports/<x>.py`` module and a contract-table row in
``tests/_import_contracts.py``; they DO NOT edit this file. That removes the
multi-train registry-collision surface.

Documented in: docs/architecture/kernel-and-ports.md
"""

import importlib

__all__ = [
    "PortRegistrationRefused",
    "UnknownPort",
    "get",
    "register",
    "register_default",
    "unregister",
]

# Ports whose adapter is NOT runtime-swappable through this registry. ``identity`` (the
# inbound-auth resolver / phase-0b trust perimeter) is refused on EVERY write path -- both
# the public override and self-registration -- so no code path can swap it at runtime.
_FROZEN_PORTS = frozenset({"identity"})

# The two internal slots. See the module docstring for the write/precedence rules.
_DEFAULTS: dict[str, object] = {}  # port -> default adapter (self-registered at import)
_OVERRIDES: dict[str, object] = {}  # port -> override adapter (public register())


class UnknownPort(LookupError):
    """``get(port)`` found no override, no self-registered default, and no importable
    ``app.ports.<port>`` module that registers one. Raised (never a silent ``None``) so
    an observer's purity rests on its OWN try/except, not on a degrading registry -- the
    house pattern of ``providers.get_provider``'s ``UnknownProviderError``.

    Base is ``LookupError``, NOT ``KeyError``: a genuine port miss must not be swallowed
    by an upstream ``except KeyError`` (a dict-style guard around unrelated code). The
    message spells out all three exhausted sources for a debuggable failure."""


class PortRegistrationRefused(RuntimeError):
    """A write to a FROZEN port (currently only ``identity``) was attempted. The
    inbound-auth resolver is not runtime-swappable by design (phase-0b security posture);
    this hard refusal is the mechanical guarantee, pinned by Train H's test."""


def _refuse_if_frozen(port: str) -> None:
    if port in _FROZEN_PORTS:
        raise PortRegistrationRefused(
            f"port {port!r} is not runtime-swappable: its adapter is frozen by design "
            f"(the inbound-auth resolver / trust perimeter). No register() or "
            f"register_default() path may replace it."
        )


def register_default(port: str, adapter: object) -> None:
    """Self-register a port's DEFAULT adapter (called by ``app.ports.<port>`` at import).

    ``setdefault`` semantics: the FIRST default registered for a port wins; a repeat or
    re-entrant call never clobbers it. Frozen ports (``identity``) are refused here too,
    so the inbound-auth resolver cannot be installed as a swappable default either."""
    _refuse_if_frozen(port)
    _DEFAULTS.setdefault(port, adapter)


def register(port: str, adapter: object) -> None:
    """Install an OVERRIDE adapter for ``port`` (tests, hot-swap). Consulted BEFORE the
    default by ``get``. ``register("identity", ...)`` RAISES ``PortRegistrationRefused``."""
    _refuse_if_frozen(port)
    _OVERRIDES[port] = adapter


def unregister(port: str) -> None:
    """Remove ``port``'s OVERRIDE (if any), returning resolution to the default. The
    sanctioned cleanup for a test that called ``register`` -- so suites never poke the
    private dicts. Pops ``_OVERRIDES`` ONLY: it can NEVER undo a self-registered default
    in ``_DEFAULTS`` (there is deliberately no public way to unwind a self-registration).
    Refuses the frozen ``identity`` port like the other write paths, and is a no-op if no
    override is set."""
    _refuse_if_frozen(port)
    _OVERRIDES.pop(port, None)


def get(port: str) -> object:
    """Resolve the active adapter for ``port``: override first, then default; on a double
    miss lazily import ``app.ports.<port>`` (which self-registers its default) and
    RE-CHECK overrides-first. A NEW port module resolves here WITHOUT any edit to this
    (frozen) file. Raises ``UnknownPort`` on a genuine miss."""
    if port in _OVERRIDES:
        return _OVERRIDES[port]
    if port in _DEFAULTS:
        return _DEFAULTS[port]
    # Double miss: force the port module to load and self-register its default.
    try:
        importlib.import_module(f"{__name__}.{port}")
    except ModuleNotFoundError as exc:
        # Distinguish "no such port module" (a genuine miss -> UnknownPort) from a port
        # module that EXISTS but whose OWN import chain is broken (a real bug we must NOT
        # mask as UnknownPort). Match ONLY the port module's own dotted name -- EXACT, not
        # also the bare ``port``: a port module (e.g. app/ports/redis.py) whose body does
        # ``import redis`` and fails raises ModuleNotFoundError(name="redis"); the bare-name
        # arm would have masked that real bug as UnknownPort. ModuleNotFoundError.name names
        # the module that was actually missing.
        if exc.name == f"{__name__}.{port}":
            raise UnknownPort(
                f"no adapter registered for port {port!r}: no override, no default, and "
                f"no importable app.ports.{port}"
            ) from exc
        raise
    # Re-check, overrides STILL first: an override set before this import still wins.
    if port in _OVERRIDES:
        return _OVERRIDES[port]
    if port in _DEFAULTS:
        return _DEFAULTS[port]
    # The module imported but did not self-register a default for this port.
    raise UnknownPort(
        f"no adapter registered for port {port!r}: app.ports.{port} imported but did not "
        f"register_default({port!r}, ...), and no override is set"
    )
