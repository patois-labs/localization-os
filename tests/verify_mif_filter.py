def test_units_and_identity():
    r = _f().parse(MIF_B)
    got = [(u.style, u.text) for u in r.units]
    assert got == EXPECTED, got
    assert r.skeleton["mif_version"] == "2019"
    m = r.units[3].inline_map
    assert m["x1"].startswith("<Variable") and "Product" in m["x1"], m
    assert m["x3"].startswith("<XRef") and m["x3"].endswith("<XRefEnd >"), m["x3"]
    assert "Getting started on page 1" in m["x3"] and "<FNote 3>" not in m["x3"], m["x3"]
    assert "Emphasis" in m["g2"] and "<FTag `'>" in m["/g2"], m
    # identity: untouched, and translations equal to the source
    assert _f().build(MIF_B, {}) == MIF_B
    same = {str(u.p_index): u.text for u in r.units}
    assert _f().build(MIF_B, same) == MIF_B
    # CRLF + BOM identity
    crlf = b"\xef\xbb\xbf" + MIF_B.replace(b"\n", b"\r\n")
    r2 = _f().parse(crlf)
    assert [(u.style, u.text) for u in r2.units] == EXPECTED
    assert _f().build(crlf, {}) == crlf
    # MIF 8.00 header is accepted too
    r3 = _f().parse(MIF_B.replace(b"<MIFFile 2019>", b"<MIFFile 8.00>"))
    assert len(r3.units) == len(EXPECTED)
    print("  [units] paragraphs, styles, tokens, identity (LF, CRLF+BOM) OK")


def test_translated_round_trip():
    f = _f()
    tr = {
        "2": "Erste Schritte",
        "3": "Willkommen bei ⟦x1⟧. Drücken Sie ⟦g2⟧Speichern⟦/g2⟧, "
        "um Ihre Arbeit zu behalten, siehe ⟦x3⟧.",
        "4": "Nutzen Sie `Zitate', ein > Zeichen,\tein Back\\slash—und Café⟦x1⟧\nZweite Zeile.",
    }
    out = f.build(MIF_B, tr)
    text = out.decode("utf-8")
    r = f.parse(out)
    got = {u.p_index: u.text for u in r.units}
    assert got[2] == tr["2"] and got[3] == tr["3"], got
    assert got[4] == tr["4"], (got[4], tr["4"])
    assert got[0] == "Cell text" and got[1] == "See the manual."
    assert "<String `Nutzen Sie \\QZitate\\q, ein \\> Zeichen,\\tein Back\\\\slash" in text, text
    assert "<Char HardReturn>" in text and "<MText `quotes'>" in text
    assert "<FNote 3>" in text and "<XRefSrcText `1001: Heading1: Getting started'>" in text
    assert "<PgfNumString `1.'>" in text and "<TextRectID 7>" in text
    assert "<TextRectID 8>" not in text  # line layout of a rebuilt paragraph is reflowed
    # untouched regions identical: everything before the TextFlow body
    head = MIF[: MIF.index(" <Para\n  <Unique 1001>")]
    assert text.startswith(head)
    assert text.endswith(MIF[MIF.index(" <Para\n  <PgfTag `Body'>\n  <ParaLine\n   <ATbl 1>") :])
    # dropped tokens are appended (anchors survive), unknown and duplicate tokens dropped
    out2 = f.build(MIF_B, {"3": "Kurz ⟦x9⟧ ⟦x1⟧ ⟦g2⟧k⟦/g2⟧ ⟦x1⟧"}).decode("utf-8")
    p = f.parse(out2.encode("utf-8")).units[3].text
    assert p == "Kurz  ⟦x1⟧ ⟦g2⟧k⟦/g2⟧ ", p  # appended tokens trail the text
    assert out2.count("<XRefEnd >") == 1 and out2.count("<FTag `Emphasis'>") == 1
    assert out2.count("<FNote 3>") == 1 and out2.count("<VariableName `Product'>") == 2
    # control characters never reach a string
    out3 = f.build(MIF_B, {"2": "A\x00B\x07C"}).decode("utf-8")
    assert "<String `ABC'>" in out3
    print("  [build] translated paragraphs, escapes, HardReturn, tokens kept OK")


def _refused(data, exc=(ValueError,), needle=""):
    try:
        _f().parse(data)
    except exc as e:
        assert needle in str(e), (needle, str(e))
        return
    raise AssertionError(f"expected a refusal for {data[:60]!r}")


def test_hostile_inputs():
    from app import config

    _refused(
        MIF_B.replace(b"<MIFFile 2019>", b"<MIFFile 7.00>"), (UnsupportedEncodingError,), "MIF 7"
    )
    _refused(
        MIF_B.replace(b"<MIFFile 2019>", b"<MIFFile 5.50>"),
        (UnsupportedEncodingError,),
        "FrameMaker 8",
    )
    _refused(b"<Book 2019>\n<BookComponent>\n", (ValueError,), "chapter")
    _refused(b"hello world", (ValueError,), "MIFFile")
    _refused(
        "<MIFFile 2019>\n<Para <ParaLine <String `café'>>>".encode("latin-1"),
        (UnsupportedEncodingError,),
        "UTF-8",
    )
    _refused(
        b"<MIFFile 2019>\n<Para <ParaLine <String `open>>>\n", (ValueError,), "could not be read"
    )
    _refused(b"<MIFFile 2019>\n<Para <ParaLine >\n", (ValueError,), "never closed")
    _refused(b"<MIFFile 2019>\n>>\n", (ValueError,), "unbalanced")
    _refused(b"<MIFFile 2019>\n" + b"<A " * 300 + b">" * 300, (InputLimitError,), "nested")
    old = config.MAX_DOCUMENT_SEGMENTS
    config.MAX_DOCUMENT_SEGMENTS = 2
    try:
        paras = b"".join(b"<Para <ParaLine <String `Para %d'>>>\n" % i for i in range(3))
        _refused(b"<MIFFile 2019>\n" + paras, (InputLimitError,), "segments")
        _refused(b"<MIFFile 2019>\n" + b"<X 1>" * 401, (InputLimitError,), "statements")
    finally:
        config.MAX_DOCUMENT_SEGMENTS = old
    _refused(
        b"<MIFFile 2019>\n<Para <ParaLine <String `"
        + b"x" * (config.MAX_SEGMENT_CHARS + 1)
        + b"'>>>",
        (InputLimitError,),
    )
    # a source paragraph that already holds marker characters is skipped, not mangled
    r = _f().parse("<MIFFile 2019>\n<Para <ParaLine <String `a ⟦x1⟧ b'>>>\n".encode())
    assert not r.units and r.skeleton["skipped_marker_paragraphs"] == 1
    # pathological escapes and long text stay linear
    import time

    big = b"<MIFFile 2019>\n<Para <ParaLine <String `" + b"\\x" * 40000 + b"'>>>\n"
    t0 = time.monotonic()
    r = _f().parse(big)
    assert len(r.units) == 1 and time.monotonic() - t0 < 5
    print("  [hostile] old MIF, book, encodings, malformed, nesting, budgets and caps refused OK")


def test_api_surface():
    from fastapi.testclient import TestClient
    from sqlmodel import Session

    from app.db import engine, init_db
    from app.main import app
    from app.models import Project, Role, TargetLocale
    from app.services import apikeys, security
    from tests._cli_runner import run_cli

    init_db()
    with Session(engine) as s:
        p = Project(name="mif", org_id=1, source_locale="en-US", default_provider="mock")
        s.add(p)
        s.commit()
        s.refresh(p)
        s.add(TargetLocale(project_id=p.id, locale=LOC))
        s.commit()
        pid = p.id
    user = security.create_user("mif@x.test", "mif", Role.ADMIN, "mif-pw-123456")
    _row, raw = apikeys.create_key(user.id, "mif", scopes="api docs admin")
    client = TestClient(app, raise_server_exceptions=False, follow_redirects=False)
    hdr = {"X-Loc-Token": raw}  # pregate: allow-secret throwaway test key
    r = client.post(
        "/api/documents",
        headers=hdr,
        data={"project_id": str(pid)},
        files={"file": ("guide.mif", MIF_B, "application/vnd.mif")},
    )
    assert r.status_code in (200, 201), (r.status_code, r.text)
    doc_id = r.json()["document_id"]
    code, out, err = run_cli(["doc", "translate", str(doc_id), "--locale", LOC])
    assert code == 0, (code, out, err)
    r = client.get(f"/api/documents/{doc_id}/download", headers=hdr, params={"locale": LOC})
    assert r.status_code == 200, (r.status_code, r.text)
    assert r.headers["content-type"].startswith("application/vnd.mif"), r.headers
    back = _f().parse(r.content)
    assert len(back.units) == len(EXPECTED)
    assert back.units[2].text != "Getting started" and "Getting started" in back.units[2].text
    assert b"<VariableName `Product'>" in r.content and b"=FrameImage" in r.content
    r = client.post(
        "/api/documents",
        headers=hdr,
        data={"project_id": str(pid)},
        files={"file": ("old.mif", b"<MIFFile 7.00>\n<Para>\n", "application/vnd.mif")},
    )
    assert 400 <= r.status_code < 500 and "MIF 7" in r.text, (r.status_code, r.text)
    print("  [api] upload, translate, download MIF; MIF 7 refused OK")


