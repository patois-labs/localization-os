def test_language_stamp():
    """Gate train-11: export stamps the TARGET language into PgfLanguage/FLanguage;
    build() stays byte-faithful; a mid-line `=x` atom is not an inset facet line."""
    from app.filters.mif_filter import fm_language

    f = _f()
    src = LANG_MIF.encode("utf-8")
    r = f.parse(src)
    assert [u.text for u in r.units] == ["Hello <PgfLanguage USEnglish> world⟦x1⟧again"], [
        u.text for u in r.units
    ]
    assert f.build(src, {}) == src
    assert f.build_localized(src, {}, None) == src
    out = f.build_localized(src, {"0": "Hallo Welt⟦x1⟧wieder"}, "de-DE").decode("utf-8")
    assert "USEnglish>" not in out.replace("USEnglish\\>", "") and "UKEnglish" not in out, out
    assert out.count("<PgfLanguage German>") == 1 and out.count("<FLanguage German>") == 2, out
    assert "<Odd =x> <Next 1>" in out
    assert [u.text for u in f.parse(out.encode("utf-8")).units] == ["Hallo Welt⟦x1⟧wieder"]
    bom = b"\xef\xbb\xbf" + src.replace(b"\n", b"\r\n")
    out2 = f.build_localized(bom, {}, "pt-BR")
    assert out2.startswith(b"\xef\xbb\xbf<MIFFile") and b"<PgfLanguage Brazilian>\r\n" in out2
    for loc, want in (
        ("en-GB", "UKEnglish"),
        ("en-US", "USEnglish"),
        ("de-CH", "SwissGerman"),
        ("fr_CA", "CanadianFrench"),
        ("zh-Hant-TW", "TraditionalChinese"),
        ("zh-TW", "TraditionalChinese"),
        ("zh-Hans", "SimplifiedChinese"),
        ("nb-NO", "Norwegian"),
        ("he", "Hebrew"),
        ("th-TH", "NoLanguage"),
    ):
        assert fm_language(loc) == want, (loc, fm_language(loc))
    print("  [lang] target PgfLanguage/FLanguage stamped on export; build() unchanged OK")


def _one_para(body: str) -> bytes:
    return (
        "<MIFFile 2019>\n<TextFlow\n <Para\n  <PgfTag `Body'>\n  <ParaLine\n"
        + body
        + "  > # end of ParaLine\n > # end of Para\n> # end of TextFlow\n"
    ).encode("utf-8")


def _font(*props: str) -> str:
    return "   <Font\n" + "".join(f"    {p}\n" for p in props) + "   > # end of Font\n"


def _s(t: str) -> str:
    return f"   <String `{t}'>\n"


BOLD = _font("<FTag `'>", "<FWeight `Bold'>", "<FLocked No>")
REGULAR = _font("<FTag `'>", "<FWeight `Regular'>", "<FLocked No>")
DEFAULT = _font("<FTag `'>", "<FLocked No>")
EMPH = _font("<FTag `Emphasis'>", "<FLocked No>")
BOLD_EMPH = _font("<FTag `Emphasis'>", "<FWeight `Bold'>", "<FLocked No>")
SIZE = _font("<FSize  14.0 pt>")
SIZE2 = _font("<FSize  16.0 pt>")


def test_font_pairs_680():
    """#680: a font change switched on and restored in the paragraph is a paired token
    that travels with its words when MT reorders them."""
    f = _f()
    # the soak repro shape: bold on the last word, restore after the last text
    src = _one_para(_s("Account ") + BOLD + _s("settings") + REGULAR)
    u = f.parse(src).units[0]
    assert u.text == "Account ⟦g1⟧settings⟦/g1⟧", u.text
    assert "Bold" in u.inline_map["g1"] and "Regular" in u.inline_map["/g1"], u.inline_map
    assert f.build(src, {"0": u.text}) == src
    out = f.build(src, {"0": "⟦g1⟧Paramètres⟦/g1⟧ du compte"}).decode("utf-8")
    assert out.index("Bold") < out.index("Paramètres") < out.index("Regular"), out
    assert out.index("Regular") < out.index(" du compte"), out
    assert f.parse(out.encode("utf-8")).units[0].text == "⟦g1⟧Paramètres⟦/g1⟧ du compte"
    # character format restored by an empty FTag; opener before the first text pulled in
    src = _one_para(EMPH + _s("Save") + DEFAULT + _s(" your work"))
    assert f.parse(src).units[0].text == "⟦g1⟧Save⟦/g1⟧ your work"
    out = f.build(src, {"0": "Ihre Arbeit ⟦g1⟧speichern⟦/g1⟧"}).decode("utf-8")
    assert out.index("Emphasis") < out.index("speichern") < out.rindex("<FTag `'>"), out
    # a pair around the whole text stays outside the unit (as before #680)
    src = _one_para(BOLD + _s("Whole") + REGULAR)
    assert f.parse(src).units[0].text == "Whole"
    # nested: emphasis inside bold, restored to bold, then to the paragraph font
    src = _one_para(
        _s("A ") + BOLD + _s("b ") + BOLD_EMPH + _s("c") + BOLD + _s(" d") + DEFAULT + _s(" e")
    )
    u = f.parse(src).units[0]
    assert u.text == "A ⟦g1⟧b ⟦g2⟧c⟦/g2⟧ d⟦/g1⟧ e", u.text
    out = f.build(src, {"0": "E ⟦g1⟧D ⟦g2⟧C⟦/g2⟧⟦/g1⟧ A"}).decode("utf-8")
    assert f.parse(out.encode("utf-8")).units[0].text == "E ⟦g1⟧D ⟦g2⟧C⟦/g2⟧⟦/g1⟧ A"
    # an emptied pair is dropped; a point token inside a pair is kept
    src = _one_para(
        _s("x ")
        + BOLD
        + _s("y ")
        + "   <Marker\n    <MType 2>\n   >\n"
        + _s("z")
        + REGULAR
        + _s(" w")
    )
    u = f.parse(src).units[0]
    assert u.text == "x ⟦g1⟧y ⟦x2⟧z⟦/g1⟧ w", u.text
    out = f.build(src, {"0": "⟦g1⟧⟦/g1⟧X ⟦x2⟧W"}).decode("utf-8")
    assert "Bold" not in out and "<MType 2>" in out, out
    # a change never restored (or not restored exactly) stays a point token
    src = _one_para(_s("a ") + SIZE + _s("b ") + SIZE2 + _s("c"))
    assert f.parse(src).units[0].text == "a ⟦x1⟧b ⟦x2⟧c"
    # ... unless the paragraph format says 16 pt is the paragraph's own size
    cat = "<PgfCatalog\n <Pgf\n  <PgfTag `Body'>\n  <PgfFont\n   <FSize  16.0 pt>\n  >\n >\n>\n"
    src2 = src.replace(b"<TextFlow", cat.encode() + b"<TextFlow")
    assert f.parse(src2).units[0].text == "a ⟦g1⟧b ⟦/g1⟧c", f.parse(src2).units[0].text
    # gate: a pair the translation breaks (missing, repeated, crossed, misnested,
    # re-kinded, close first) loses its font change and keeps its words, never a 409;
    # a pair whose enclosing pair is dropped is dropped too (its restore statement
    # returns to the enclosing font)
    src = _one_para(
        _s("A ") + BOLD + _s("b ") + BOLD_EMPH + _s("c") + BOLD + _s(" d") + DEFAULT + _s(" e")
    )
    for tr, want in (
        ("A ⟦g1⟧b c d⟦/g1⟧ e", "A ⟦g1⟧b c d⟦/g1⟧ e"),
        ("A ⟦g1⟧b ⟦g2⟧c⟦/g2⟧ d⟦/g1⟧ ⟦g1⟧e", "A ⟦g1⟧b ⟦g2⟧c⟦/g2⟧ d⟦/g1⟧ e"),
        ("A ⟦g1⟧b ⟦g2⟧c⟦/g1⟧ d⟦/g2⟧ e", "A b c d e"),
        ("A ⟦g1⟧b⟦/g1⟧ ⟦g2⟧c⟦/g2⟧ d e", "A ⟦g1⟧b⟦/g1⟧ c d e"),
        ("A ⟦x1⟧b ⟦g2⟧c⟦/g2⟧ d⟦/x1⟧ e", "A b c d e"),
        ("A ⟦/g1⟧b ⟦g2⟧c⟦/g2⟧ d⟦g1⟧ e", "A b c d e"),
    ):
        out = f.build(src, {"0": tr})
        assert f.parse(out).units[0].text == want, (tr, f.parse(out).units[0].text)
    print("  [#680] font changes are paired tokens that travel with their words OK")


