"""FrameMaker MIF document filter (format Batch 14): MIF 8 and later.

  identity    an untouched file (comments, inset facets, CRLF, BOM) rebuilds byte for byte
  units       every Para (text flow, table cell, footnote) in file order; a paragraph
              wrapped over several ParaLines is one unit; PgfTag is the style
  tokens      variables, xrefs (with their computed text), markers, font changes,
              footnote/table anchors are x point tokens; printable Char names are text
  build       translated paragraphs become one ParaLine with escaped strings; HardReturn
              splits lines; dropped tokens are appended so anchors survive; re-parse OK
  hostile     MIF 7 and older, book files, non-UTF-8, malformed, deep nesting,
              statement budget, segment and unit caps are refused
  surfaces    API upload -> translate (mock) -> download, upload label, connector map

Fixtures are hand-written here. Hermetic + offline. Final line: "MIF FILTER OK".
"""

