def test_encodings():
    src = "export default { a: 'Café ünd' }"
    cp = src.encode("cp1252")
    assert _texts(cp) == ["Café ünd"]
    assert F.build(cp, {}) == cp
    assert F.build(cp, {"0": "Kaffee"}).decode("utf-8") == "export default { a: 'Kaffee' }"
    assert F.parse(cp).skeleton.get("source_encoding") == "cp1252"
    u16 = src.encode("utf-16")
    assert _texts(u16) == ["Café ünd"]
    assert F.build(u16, {}) == u16
    assert F.build(u16, {"0": "Tee"}).decode("utf-8") == "export default { a: 'Tee' }"
    print("  [js] Windows-1252 and UTF-16 sources parsed and exported as UTF-8")


def test_end_to_end_upload_export():
    from fastapi.testclient import TestClient
    from sqlmodel import Session, select

    from app.db import engine, init_db
    from app.main import app
    from app.models import Segment

    init_db()
    client = TestClient(app)
    created = client.post(
        "/projects",
        data={"name": "JS e2e", "source_locale": "en-US", "target_locales": "de-DE"},
        follow_redirects=False,
    )
    pid = int(created.headers["location"].rsplit("/", 1)[-1])
    uploaded = client.post(
        f"/projects/{pid}/documents",
        data={"mode": "segmented"},
        files={"file": ("en.ts", TS.encode())},
        follow_redirects=False,
    )
    assert uploaded.status_code in (302, 303), uploaded.text[:400]
    did = int(uploaded.headers["location"].rsplit("/", 1)[-1])
    with Session(engine) as session:
        rows = session.exec(select(Segment).where(Segment.document_id == did)).all()
        by_src = {r.source_text: r.id for r in rows}
    assert "Part one, part two" in by_src, sorted(by_src)
    saved = client.post(
        f"/segments/{by_src['Part one, part two']}/save",
        data={"target_text": "Teil eins, Teil zwei"},
    )
    assert saved.status_code in (200, 302, 303), saved.text[:300]
    exported = client.get(f"/documents/{did}/export?locale=de-DE")
    assert exported.status_code == 200, exported.text[:300]
    assert not exported.headers.get("content-type", "").startswith("text/javascript")
    body = exported.content.decode()
    assert "concat: 'Teil eins, Teil zwei'," in body, body
    assert "export type Messages = typeof en" in body
    code = client.post(
        f"/projects/{pid}/documents",
        data={"mode": "segmented"},
        files={"file": ("app.js", b"document.title = 'Hello';\n")},
        follow_redirects=False,
    )
    from app.models import Document

    with Session(engine) as session:
        names = [
            d.filename for d in session.exec(select(Document).where(Document.project_id == pid))
        ]
    assert "app.js" not in names, (code.status_code, names)
    print("  [js] end to end: upload .ts -> save -> export; app code refused")


