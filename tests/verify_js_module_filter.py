def test_ts_extension_routing():
    """`.ts` is claimed by Qt Linguist (fmt "ts", fmt/b2-xmlres) and by this filter; the
    extension is pinned to the JS filter whatever the import order (gate fix), which
    hands XML to the Qt filter. With the REAL Qt filter registered: a Qt .ts goes to
    Qt, a TS locale module goes to js, arbitrary TypeScript is refused."""
    import importlib.util

    from app.filters import base

    assert base._ALIASES["ts"] == "js"
    ts = get_filter("ts")
    assert ts is F, ts
    ts_module = TS.encode()
    assert ts.parse(ts_module).units[0].text == "OK"
    _refused_any("export function t(k: string) { return k }\n", "function")
    _refused_any("const app = createApp(App)\napp.mount('#app')\n", "function call")
    if importlib.util.find_spec("app.filters.xml_resource") is None:
        print("  [js] .ts pinned to the JS filter (Qt filter not on this branch)")
        return
    qt_filter = base._FILTERS.get("ts")
    assert qt_filter is not None and qt_filter is not F
    assert type(qt_filter).__name__ == "QtTsFilter", type(qt_filter)
    pr = ts.parse(QT_TS)
    assert [u.text for u in pr.units] == ["Open file"], [u.text for u in pr.units]
    out = ts.build(QT_TS, {"0": "Datei offnen"}).decode("utf-8")
    assert "<translation>Datei offnen</translation>" in out, out
    loc = ts.build_localized(QT_TS, {"0": "Datei offnen"}, "de-DE").decode("utf-8")
    assert 'language="de_DE"' in loc, loc
    assert len(ts.records(QT_TS)) == 1  # the Qt filter's own records (keys bridge)
    print("  [js] real Qt .ts -> Qt filter, TS locale module -> js, other TS refused")


def test_printf_regex_linear():
    """Gate fix: the printf placeholder pattern backtracked quadratically on a long run of
    zeros after a `%` (30k zeros took 22 s); bounded quantifiers keep it linear."""
    import time

    t0 = time.monotonic()
    src = "export default { a: 'Sale %" + "0" * 60000 + "z' }"
    assert _texts(src.encode()) == ["Sale %" + "0" * 60000 + "z"]
    assert time.monotonic() - t0 < 5, time.monotonic() - t0
    for s in ("Saved %s of %1$d files", "%05.2f%%", "%(name)s left"):
        # a point token, ⟦xN⟧ or (named / numbered, #693) ⟦pN⟧
        assert "⟦" in F.parse(f"export default {{ a: 'Go {s}' }}".encode()).units[0].text
    print("  [js] printf placeholder scan stays linear on a run of zeros")


def test_caps():
    deep = "export default " + "{a:" * 40 + "'x'" + "}" * 40
    _refused_any(deep, "nested")
    old = config.MAX_DOCUMENT_SEGMENTS
    config.MAX_DOCUMENT_SEGMENTS = 5
    try:
        many = "export default {" + ",".join(f"k{i}: 'Value {i}'" for i in range(8)) + "}"
        _refused_any(many, "MAX_DOCUMENT_SEGMENTS")
        quotes = "export default [" + "''," * 300 + "]"
        _refused_any(quotes, "MAX_DOCUMENT_SEGMENTS")
        toks = "export default {}" + ";" * 400
        _refused_any(toks, "MAX_DOCUMENT_SEGMENTS")
    finally:
        config.MAX_DOCUMENT_SEGMENTS = old
    huge = "export default { a: '" + "x" * (config.MAX_SEGMENT_CHARS + 1) + "' }"
    _refused_any(huge, "MAX_SEGMENT_CHARS")
    print("  [js] caps: nesting, segment count, quote, token and length budgets")


