def _texts(data: bytes) -> list[str]:
    return [u.text for u in F.parse(data).units]


def _refused(src: str, needle: str):
    try:
        F.parse(src.encode())
    except InputLimitError as exc:
        assert needle in str(exc), (needle, str(exc))
        return str(exc)
    raise AssertionError(f"not refused: {src!r}")


def test_registered():
    exts = supported_exts()
    for ext in ("js", "mjs", "cjs", "ts", "mts", "cts"):
        assert ext in exts, ext
        assert get_filter(ext) is F, ext
    assert F.fmt == "js"
    print("  [js] registered as .js .mjs .cjs .ts .mts .cts")


def test_parse_shapes():
    assert _texts(ESM.encode()) == [
        "Home",
        "About us",
        # #693: named / numbered placeholders are free-order tokens; tags keep x
        "Hello, ⟦p1⟧!",
        "no apples | one apple | ⟦p1⟧ apples",
        "See ⟦p1⟧",
        "Write to us ⟦x1⟧ support",
        "First",
        "Second",
        "Dashed",
    ], _texts(ESM.encode())
    assert _texts(CJS.encode()) == [
        "Welcome, ⟦p1⟧!",
        "You have ⟦p1⟧ unread messages",
        "⟦p1⟧ Glad you are here.",
        "Click ⟦x1⟧here⟦x2⟧ to continue",
        "Saved ⟦x1⟧ of ⟦p2⟧ files",
    ], _texts(CJS.encode())
    ts = _texts(TS.encode())
    assert ts[:3] == ["OK", "Cancel", "Multi-line\ntemplate title"], ts
    assert ts[3] == "⟦x1⟧No items⟦x2⟧⟦x3⟧ item⟦x4⟧⟦x5⟧ items⟦x6⟧", ts[3]
    assert ts[4] == "⟦x1⟧She replied⟦x2⟧He replied⟦x3⟧They replied⟦x4⟧", ts[4]
    assert ts[5] == "Part one, part two"
    units = F.parse(TS.encode()).units
    assert units[3].inline_map["1"] == {"point": "{count, plural, =0 {"}
    assert units[3].inline_map["3"] == {"point": "#"}
    assert units[3].inline_map["6"] == {"point": "}}"}
    for other in (
        "export const en = { a: 'A' }, de = { a: 'B' };\nexport { en, de as fallback }",
        "exports.home = { title: 'Title' }",
        "const m = { a: 'A' }\nmodule.exports = m",
        "export default ({ a: 'A' })",
        "const messages = { a: 'A' };\nexport { messages as default };",
        "#!/usr/bin/env node\nexport default { a: 'A' }",
    ):
        assert _texts(other.encode())[0] == "A" or _texts(other.encode())[0] == "Title", other
    print("  [js] ESM, CommonJS, TypeScript and named-export shapes parse")


def test_records():
    recs = F.records(TS.encode())
    keys = [r["key"] for r in recs]
    assert keys == ["shared.ok", "shared.cancel", "title", "items", "gender", "concat"], keys
    assert recs[2]["value"] == "Multi-line\ntemplate title"
    assert [r["key"] for r in F.records(ESM.encode())][:3] == ["nav.home", "nav.about", "greeting"]
    assert F.records(CJS.encode())[0]["key"] == "translation.welcome"
    named = "export const en = { a: { b: 'B' } }"
    assert F.records(named.encode())[0]["key"] == "en.a.b"
    print("  [js] records(): dotted keys, default export name dropped")


def test_identity_round_trip():
    for src in (ESM, CJS, TS):
        for data in (
            src.encode(),
            src.replace("\n", "\r\n").encode(),
            b"\xef\xbb\xbf" + src.encode(),
        ):
            assert F.build(data, {}) == data
            same = {str(u.p_index): u.text for u in F.parse(data).units}
            assert F.build(data, same) == data
    print("  [js] untranslated build is byte-identical (LF, CRLF, BOM)")


def test_translated_round_trip():
    data = ESM.encode()
    out = F.build(data, {"0": "Startseite", "2": "Hallo, ⟦x1⟧!", "6": "Erste"}).decode()
    assert "home: 'Startseite'," in out, out
    assert "greeting: 'Hallo, {name}!'," in out
    assert "list: ['Erste', 'Second', '---']," in out
    assert (
        out.replace("Startseite", "Home").replace("Hallo", "Hello").replace("Erste", "First") == ESM
    )
    crlf = ESM.replace("\n", "\r\n").encode()
    out2 = F.build(crlf, {"1": "Über uns"}).decode("utf-8")
    assert 'about: "Über uns",\r\n' in out2 and out2.count("\r\n") == ESM.count("\n")
    bom = b"\xef\xbb\xbf" + ESM.encode()
    assert F.build(bom, {"0": "Start"}).startswith(b"\xef\xbb\xbf// Generated")
    ts = TS.encode()
    out3 = F.build(
        ts, {"2": "Mehrzeiliger\nTitel", "3": "⟦x1⟧Keine⟦x2⟧⟦x3⟧ Ding⟦x4⟧⟦x5⟧ Dinge⟦x6⟧"}
    )
    text = out3.decode()
    assert "title: `Mehrzeiliger\nTitel`," in text, text
    assert "items: '{count, plural, =0 {Keine} one {# Ding} other {# Dinge}}'," in text
    out4 = F.build(ts, {"5": "Teil eins und zwei"}).decode()
    assert "concat: 'Teil eins und zwei'," in out4, out4
    assert _texts(out3)[2] == "Mehrzeiliger\nTitel"
    print("  [js] translated build splices only changed literals")


def test_escapes_per_quote():
    src = "export default { a: 'A', b: \"B\", c: `C`, d: 'D' }"
    nasty = 'It\'s "quoted" \\ back ${x} `tick`\nnew\ttab '
    out = F.build(src.encode(), {"0": nasty, "1": nasty, "2": nasty}).decode()
    assert "a: 'It\\'s \"quoted\" \\\\ back ${x} `tick`\\nnew\\ttab\\u2028'" in out, out
    assert 'b: "It\'s \\"quoted\\" \\\\ back ${x} `tick`\\nnew\\ttab\\u2028"' in out, out
    assert 'c: `It\'s "quoted" \\\\ back \\${x} \\`tick\\`\\nnew\\ttab\\u2028`' in out, out
    # the rebuilt file reads back to exactly the translated values (placeholders aside)
    assert is_js_locale_module(out.encode())
    recs = F.records(out.encode())
    assert [r["value"] for r in recs[:3]] == [nasty] * 3, recs
    dec = r"export default { e: 'It\'s \x41é\u{1F600}😀 a\
b \0 end', f: `t\`ick` }"
    assert _texts(dec.encode()) == ["It's Aé\U0001f600\U0001f600 ab \0 end", "t`ick"]
    print("  [js] escapes decoded per ECMAScript and re-escaped per quote style")


def test_placeholders_and_unknown_tokens():
    src = "export default { a: 'Hi {{name}}, %s and {count} <b>bold</b>' }"
    u = F.parse(src.encode()).units[0]
    assert u.text == "Hi ⟦p1⟧, ⟦x2⟧ and ⟦p3⟧ ⟦x4⟧bold⟦x5⟧", u.text  # #693
    # a dropped token is dropped; an invented token is not written into the file
    out = F.build(src.encode(), {"0": "Hallo ⟦x1⟧ ⟦x9⟧ ⟦g1⟧fett⟦/g1⟧"}).decode()
