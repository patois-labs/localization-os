"""SSA / ASS subtitle filter (Batch 10, app/filters/ass_filter.py).

  identity    parse then build with no translations is byte-identical (LF, CRLF, BOM).
  fields      only the Text field (10th, may hold commas) of Dialogue lines and the
              [Script Info] Title are units; Comment lines, styles, other fields stay.
  tokens      {\\...} override blocks, \\N \\n \\h are point tokens; leading/trailing
              ones are hoisted out of the unit; build puts the source tokens back.
  format      a custom Format line (fewer fields) moves the Text split point.
  drawing     a \\p1 drawing line is never a unit.
  encodings   cp1252 converts; UTF-16 BOM converts; undecodable binary refused.
  hostile     over-long Text field and too many units are refused (InputLimitError).
  pipeline    API upload -> CLI translate (mock) -> API download keeps the tags.

Hermetic + offline. Final line: "ASS FILTER OK".
"""

