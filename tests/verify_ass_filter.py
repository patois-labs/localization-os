def test_units_and_identity():
    data = ASS.encode("utf-8")
    units = [u.text for u in _ass().parse(data).units]
    assert units == [
        "The Long Night",
        "Hello, world, how are you?",
        "I said ⟦g1⟧no⟦/g1⟧.⟦x2⟧Never again.",
        "Wait⟦x1⟧for it⟦x2⟧... ⟦x3⟧now",
    ], units
    assert _ass().build(data, {}) == data
    crlf = ASS.replace("\n", "\r\n").encode("utf-8")
    assert _ass().build(crlf, {}) == crlf
    bom = b"\xef\xbb\xbf" + data
    assert [u.text for u in _ass().parse(bom).units] == units
    assert _ass().build(bom, {}) == bom
    mixed = b"[Events]\r\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Hi\nComment: x\r\n"
    assert _ass().build(mixed, {}) == mixed
    no_eol = b"[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Hi there"
    assert _ass().build(no_eol, {}) == no_eol
    print("  [identity] untouched build is byte-identical (LF, CRLF, mixed, BOM, no final EOL) OK")


def test_gate_lines_language():
    # A U+2028 / U+0085 / form feed inside a Text field does not end the line (libass
    # splits on CR/LF only): the whole field is one unit and translates as one.
    odd = (
        "[Events]\n"
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
        "Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,One two\x0cthree, four\n"
        "Dialogue: 0,0:00:03.00,0:00:04.00,Default,,0,0,0,,Keep ⟦x9⟧ as is\n"
    )
    data = odd.encode("utf-8")
    units = [u.text for u in _ass().parse(data).units]
    assert units == ["One two\x0cthree, four", "Keep ⟦x9⟧ as is"], units
    out = _ass().build(data, {"0": "Eins zwei drei, vier"}).decode("utf-8")
    assert ",,Eins zwei drei, vier\n" in out and "three" not in out, out
    # an untouched line keeps literal bracket text byte for byte
    assert "Keep ⟦x9⟧ as is" in out, out
    # localized export: libass Language header set, or added after [Script Info]
    data2 = ASS.replace("\n", "\r\n").encode("utf-8")
    loc = _ass().build_localized(data2, {}, "de-DE").decode("utf-8")
    assert loc.startswith("[Script Info]\r\nLanguage: de\r\n"), loc[:80]
    assert _ass().build_localized(data2, {}, None) == data2
    with_lang = ASS.replace("ScriptType", "Language: en\nScriptType").encode("utf-8")
    loc2 = _ass().build_localized(with_lang, {}, "pt-BR").decode("utf-8")
    assert "Language: pt\n" in loc2 and "Language: en" not in loc2, loc2[:200]
    assert loc2.count("Language:") == 1
    loc3 = _ass().build_localized(with_lang, {}, "fil-PH").decode("utf-8")
    assert "Language:" not in loc3, "a target with no 2-letter code drops the stale header"
    print("  [gate] CR/LF-only line split, verbatim untouched lines, Language header OK")


def test_translated_round_trip():
    data = ASS.encode("utf-8")
    out = (
        _ass()
        .build(
            data,
            {
                "0": "La longue nuit",
                "1": "Bonjour, le monde, comment vas-tu ?",
                "2": "J'ai dit ⟦g1⟧non⟦/g1⟧.⟦x2⟧Plus jamais.",
                "3": "Attends⟦x1⟧le⟦x2⟧... ⟦x3⟧maintenant",
            },
        )
        .decode("utf-8")
    )
    lines = out.split("\n")
    assert "Title: La longue nuit" in lines, out
    assert (
        "Dialogue: 0,0:00:01.00,0:00:04.00,Default,Anna,0,0,0,,Bonjour, le monde, comment vas-tu ?"
        in lines
    ), out
    assert "Comment: 0,0:00:01.00,0:00:04.00,Default,,0,0,0,,Do not translate this note" in lines
    assert (
        "Dialogue: 0,0:00:05.00,0:00:07.50,Default,,0,0,0,,"
        "{\\an8}J'ai dit {\\i1}non{\\i0}.\\NPlus jamais." in lines
    ), out
    assert "Dialogue: 0,0:00:08.00,0:00:09.00,Default,,0,0,0,,{\\pos(400,570)}" in lines
    assert (
        "Dialogue: 1,0:00:10.00,0:00:11.00,Default,,0,0,0,,{\\p1}m 0 0 l 100 0 100 100 0 100{\\p0}"
        in lines
    )
    assert (
        "Dialogue: 0,0:00:12.00,0:00:13.00,Default,,0,0,0,,"
        "Attends\\hle\\n... {fix timing}maintenant\\N" in lines
    ), out
    assert "[V4+ Styles]" in lines and lines[-1] == "", out
    # Re-parse: same unit count, same token shape.
    again = [u.text for u in _ass().parse(out.encode("utf-8")).units]
    assert again[2] == "J'ai dit ⟦g1⟧non⟦/g1⟧.⟦x2⟧Plus jamais.", again
    print("  [translate] Text field, Title replaced; commas, tags, timings, comments kept OK")


def test_translation_edge_cases():
    data = (
        b"[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,One {\\b1}two{\\b0} three\n"
    )
    # A real newline in the translation becomes \N; unknown markers are dropped.
    assert _ass().parse(data).units[0].text == "One ⟦g1⟧two⟦/g1⟧ three"
    out = _ass().build(data, {"0": "Un ⟦g1⟧deux⟦/g1⟧\ntrois⟦x9⟧⟦g7⟧"}).decode("utf-8")
    assert out.endswith(",,Un {\\b1}deux{\\b0}\\Ntrois\n"), out
    # A Title translation never gets a line break.
    t = b"[Script Info]\nTitle: A\n"
    assert _ass().build(t, {"0": "B\nC"}) == b"[Script Info]\nTitle: B C\n"
    # <untitled> and blank titles are not units; Title outside Script Info is not either.
    for raw in (
        b"[Script Info]\nTitle: <untitled>\n",
        b"[Script Info]\nTitle:\n",
        b"[Aegisub Project Garbage]\nTitle: x\n",
    ):
        assert _ass().parse(raw).units == [], raw
    print("  [edge] newline -> \\N, stray markers dropped, Title one line, <untitled> skipped OK")


def test_style_switch_pairs_680():
    """#680: a switch turned on and off in the same line is a paired token, so a
    reordered translation moves it with its words; build writes it balanced."""
    head = "[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,"

    def unit(text):
        return [u.text for u in _ass().parse((head + text + "\n").encode()).units]

    def build(text, tr):
        out = _ass().build((head + text + "\n").encode(), {"0": tr}).decode("utf-8")
        return out.split("0,0,0,,", 1)[1].rstrip("\n")

    # the closing switch after the last word is part of the unit
    assert unit("Account {\\i1}settings{\\i0}") == ["Account ⟦g1⟧settings⟦/g1⟧"]
    assert build("Account {\\i1}settings{\\i0}", "⟦g1⟧Paramètres⟦/g1⟧ du compte") == (
        "{\\i1}Paramètres{\\i0} du compte"
    )
    # an opener before the first word is pulled in; positioning blocks stay outside
    assert unit("{\\an8}{\\b1}Account{\\b0} settings") == ["⟦g1⟧Account⟦/g1⟧ settings"]
    assert build("{\\an8}{\\b1}Account{\\b0} settings", "Paramètres du ⟦g1⟧compte⟦/g1⟧") == (
        "{\\an8}Paramètres du {\\b1}compte{\\b0}"
    )
    # a switch around the whole line stays outside the unit
    assert unit("{\\an8}{\\i1}Whole line{\\i0}") == ["Whole line"]
    assert build("{\\an8}{\\i1}Whole line{\\i0}", "Ligne") == "{\\an8}{\\i1}Ligne{\\i0}"
    # nested switches ended by one {\r}: separated, the inner one writes its own off
    # switch and the outermost keeps the {\r} (gate: it also resets a colour set in
    # between, which must not run on into the rest of the line)
    assert unit("{\\b1}a {\\i1}b{\\r} c") == ["⟦g1⟧a ⟦g2⟧b⟦/g2⟧⟦/g1⟧ c"]
    assert build("{\\b1}a {\\i1}b{\\r} c", "⟦g2⟧B⟦/g2⟧ ⟦g1⟧A⟦/g1⟧ C") == (
        "{\\i1}B{\\i0} {\\b1}A{\\r} C"
    )
    src = "Say {\\i1}very {\\b1}{\\c&H0000FF&}loud{\\r} now"
    assert unit(src) == ["Say ⟦g1⟧very ⟦g2⟧⟦x3⟧loud⟦/g2⟧⟦/g1⟧ now"]
    out = build(src, "Dis ⟦g1⟧très ⟦g2⟧⟦x3⟧fort⟦/g2⟧⟦/g1⟧ maintenant")
    assert out.endswith("fort{\\b0}{\\r} maintenant"), out
    # crossed switches keep the pre-#680 point tokens for the one that does not nest
    assert unit("x {\\b1}a{\\i1}b{\\b0}c{\\i0} d") == ["x ⟦g1⟧a⟦x2⟧b⟦/g1⟧c⟦x3⟧ d"]
    # balanced output: a pair MT emptied is dropped; a stray close is dropped and an
    # unclosed open is closed at the end of the line
    assert build("x {\\b1}a{\\b0} y", "X Y ⟦g1⟧⟦/g1⟧") == "X Y "
    assert build("x {\\b1}a{\\b0} y", "X ⟦/g1⟧Y ⟦g1⟧A") == "X Y {\\b1}A{\\b0}"
    print("  [pairs] #680 style switches travel with their words, balanced OK")


def test_custom_format_and_ssa():
    ssa = (
        b"[Script Info]\nScriptType: v4.00\n\n[Events]\n"
        b"Format: Marked, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
        b"Dialogue: Marked=0,0:00:01.00,0:00:02.00,*Default,NTP,0000,0000,0000,!Effect,Hi, you\n"
    )
    assert [u.text for u in _ass().parse(ssa).units] == ["Hi, you"]
    short = (
        b"[Events]\nFormat: Start, End, Text\nDialogue: 0:00:01.00,0:00:02.00,Short, form, text\n"
    )
    assert [u.text for u in _ass().parse(short).units] == ["Short, form, text"]
    out = _ass().build(short, {"0": "Forme, courte"}).decode("utf-8")
    assert out.endswith("Dialogue: 0:00:01.00,0:00:02.00,Forme, courte\n"), out
    # Text not last in Format: the lines are left alone rather than guessed at.
    odd = b"[Events]\nFormat: Text, Start\nDialogue: Hi,0:00:01.00\n"
    assert _ass().parse(odd).units == []
    # Too few fields: malformed line is copied verbatim.
    bad = b"[Events]\nDialogue: 0,0:00:01.00,Hello\n"
    assert _ass().parse(bad).units == [] and _ass().build(bad, {}) == bad
    print("  [format] SSA v4 Marked field, custom Format split, malformed lines kept OK")


def test_encodings():
    cp = ("[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Café crème\n").encode(
        "cp1252"
    )
    res = _ass().parse(cp)
    assert [u.text for u in res.units] == ["Café crème"]
    assert res.skeleton.get("source_encoding") == "cp1252", res.skeleton
    out = _ass().build(cp, {"0": "Kaffee"})
    assert out.decode("utf-8").endswith(",,Kaffee\n"), out
    u16 = ("[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Grüße\n").encode("utf-16")
    assert [u.text for u in _ass().parse(u16).units] == ["Grüße"]
    assert _ass().build(u16, {}) == u16  # B-bytes: untouched = as uploaded
    built = _ass().build(u16, {"0": "Grüße!"})
    assert built.startswith(b"\xef\xbb\xbf") and built[3:].decode("utf-8").endswith(",,Grüße!\n"), (
        built
    )
    try:
        _ass().parse(b"\x00\x01\x02\x81\x8d\x8f" * 50)
    except InputLimitError:
        pass
    else:
        raise AssertionError("a binary .ass upload must be refused")
    print("  [encoding] cp1252 + UTF-16 converted to UTF-8, binary refused OK")


def test_hostile_caps():
    from app import config

    long_text = "x" * (config.MAX_SEGMENT_CHARS + 10)
    data = f"[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,{long_text}\n".encode()
    try:
        _ass().parse(data)
    except InputLimitError:
        pass
    else:
        raise AssertionError("an over-long Text field must be refused")
    old = config.MAX_DOCUMENT_SEGMENTS
    config.MAX_DOCUMENT_SEGMENTS = 3
    try:
        many = "[Events]\n" + "Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Hi\n" * 5
        try:
            _ass().parse(many.encode())
        except InputLimitError:
            pass
        else:
            raise AssertionError("more units than MAX_DOCUMENT_SEGMENTS must be refused")
        try:
            _ass().parse(b"\n" * 70)
        except InputLimitError:
            pass
        else:
            raise AssertionError("the line budget must refuse a file of blank lines")
    finally:
        config.MAX_DOCUMENT_SEGMENTS = old
    # Unclosed brace is literal text; a giant override block is one token.
    weird = b"[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,Hi {there\n"
    assert [u.text for u in _ass().parse(weird).units] == ["Hi {there"]
    assert _ass().build(weird, {}) == weird
    print("  [hostile] long field, unit cap, line budget refused; unclosed brace literal OK")


