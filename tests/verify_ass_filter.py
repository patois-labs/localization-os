def test_pipeline_api_cli():
    from fastapi.testclient import TestClient
    from sqlmodel import Session, select

    from app.db import engine, init_db
    from app.main import app
    from app.models import Project, Role, Segment, TargetLocale
    from app.services import apikeys, security
    from tests._cli_runner import run_cli

    init_db()
    with Session(engine) as s:
        p = Project(name="assflt", org_id=1, source_locale="en-US", default_provider="mock")
        s.add(p)
        s.commit()
        s.refresh(p)
        s.add(TargetLocale(project_id=p.id, locale=LOC))
        s.commit()
        pid = p.id
    user = security.create_user("assflt@x.test", "assflt", Role.ADMIN, "assflt-pw-123456")
    _row, raw = apikeys.create_key(user.id, "assflt", scopes="api docs admin")
    client = TestClient(app, raise_server_exceptions=False, follow_redirects=False)
    hdr = {"X-Loc-Token": raw}  # pregate: allow-secret throwaway test key
    r = client.post(
        "/api/documents",
        headers=hdr,
        data={"project_id": str(pid)},
        files={"file": ("episode.ass", ASS.encode("utf-8"), "text/x-ssa")},
    )
    assert r.status_code in (200, 201), (r.status_code, r.text)
    doc_id = r.json()["document_id"]
    with Session(engine) as s:
        srcs = [
            x.source_text
            for x in s.exec(
                select(Segment)
                .where(Segment.document_id == doc_id, Segment.target_locale == LOC)
                .order_by(Segment.order_index)
            ).all()
        ]
    assert any("⟦x1⟧" in t for t in srcs), srcs
    assert not any("Do not translate" in t for t in srcs), srcs
    code, out, err = run_cli(["doc", "translate", str(doc_id), "--locale", LOC])
    assert code == 0, (code, out, err)
    r = client.get(f"/api/documents/{doc_id}/download", headers=hdr, params={"locale": LOC})
    assert r.status_code == 200, (r.status_code, r.text)
    text = r.content.decode("utf-8")
    assert "Comment: 0,0:00:01.00,0:00:04.00,Default,,0,0,0,,Do not translate this note" in text, (
        text
    )
    assert "{\\an8}" in text and "{\\i1}" in text and "{\\i0}" in text and "\\N" in text, text
    assert "⟦" not in text and "⟧" not in text, text
    assert "[V4+ Styles]" in text and "Dialogue: 1,0:00:10.00" in text, text
    assert f"[{LOC}]" in text, text
    print("  [pipeline] API upload, CLI mock translate, API download keep tags + comments OK")


